export type TranslationKey = keyof typeof translations.es

interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, values?: Record<string, string | number>) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function detectLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_KEY)
  if (stored && LANGUAGES.some((item) => item.code === stored)) return stored as Language
  // Plataforma internacional: si el navegador no está en español, arrancamos en inglés.
  const preferred = typeof navigator !== 'undefined' ? navigator.language.slice(0, 2).toLowerCase() : ''
  return preferred && preferred !== 'es' ? 'en' : DEFAULT_LANGUAGE
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(detectLanguage)

  function setLanguage(nextLanguage: Language) {
    localStorage.setItem(STORAGE_KEY, nextLanguage)
    setLanguageState(nextLanguage)
  }

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values = {}) => {
      const dictionary = translations[language] as Record<TranslationKey, string>
      const fallback = translations[DEFAULT_LANGUAGE] as Record<TranslationKey, string>
      let message = dictionary[key] ?? fallback[key] ?? key
      for (const [name, replacement] of Object.entries(values)) {
        message = message.replaceAll('{{' + name + '}}', String(replacement))
      }
      return message
    },
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}
